export function computeJuryAverages(grades: JuryMemberGrade[]) {
  if (!grades.length) {
    return { dossierScore: 0, projectScore: 0, interviewScore: 0, total: 0 };
  }
  const n = grades.length;
  const dossierScore = Math.round(
    grades.reduce((acc, g) => acc + g.dossierScore, 0) / n
  );
  const projectScore = Math.round(
    grades.reduce((acc, g) => acc + g.projectScore, 0) / n
  );
  const interviewScore = Math.round(
    grades.reduce((acc, g) => acc + g.interviewScore, 0) / n
  );
  return {
    dossierScore,
    projectScore,
    interviewScore,
    total: dossierScore + projectScore + interviewScore,
  };
}

